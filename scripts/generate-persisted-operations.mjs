import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import { Kind, parse, print, visit } from "graphql"

const operationsPath = new URL(
  "../apps/web/src/app/api/operations.graphql",
  import.meta.url,
)
const workerOutput = new URL(
  "../apps/game-worker/src/graphql/persistedOperations.generated.ts",
  import.meta.url,
)
const webOutput = new URL(
  "../apps/web/src/app/api/persistedOperationIds.generated.ts",
  import.meta.url,
)

const source = await readFile(operationsPath, "utf8")
const parsed = parse(source)
/** @type {Map<string, import("graphql").FragmentDefinitionNode>} */
const fragments = new Map()
for (const definition of parsed.definitions) {
  if (definition.kind === Kind.FRAGMENT_DEFINITION) {
    fragments.set(definition.name.value, definition)
  }
}
/**
 * @param {import("graphql").OperationDefinitionNode} operation
 * @returns {import("graphql").FragmentDefinitionNode[]}
 */
const referencedFragments = operation => {
  /** @type {Map<string, import("graphql").FragmentDefinitionNode>} */
  const selected = new Map()
  /** @param {import("graphql").ASTNode} node */
  const collect = node => {
    visit(node, {
      FragmentSpread(spread) {
        const fragment = fragments.get(spread.name.value)
        if (!fragment || selected.has(spread.name.value)) return
        selected.set(spread.name.value, fragment)
        collect(fragment)
      },
    })
  }
  collect(operation)
  return [...selected.values()].sort((left, right) =>
    left.name.value.localeCompare(right.name.value),
  )
}
const operations = parsed.definitions
  .filter(definition => definition.kind === Kind.OPERATION_DEFINITION)
  .map(operation => {
    if (!operation.name?.value) {
      throw new Error("Iedere persisted GraphQL-operatie moet een naam hebben.")
    }
    const document = print({
      kind: Kind.DOCUMENT,
      definitions: [operation, ...referencedFragments(operation)],
    })
    const sha256Hash = createHash("sha256").update(document).digest("hex")
    return { operationName: operation.name.value, sha256Hash, document }
  })
  .sort((left, right) => left.operationName.localeCompare(right.operationName))

const workerEntries = operations
  .map(
    operation =>
      `  ${JSON.stringify(operation.sha256Hash)}: ${JSON.stringify({
        operationName: operation.operationName,
        document: operation.document,
      })},`,
  )
  .join("\n")
const webEntries = operations
  .map(
    operation =>
      `  ${JSON.stringify(operation.operationName)}: ${JSON.stringify(operation.sha256Hash)},`,
  )
  .join("\n")

const banner =
  "// Generated by scripts/generate-persisted-operations.mjs. Do not edit.\n"
await Promise.all([
  writeFile(
    workerOutput,
    `${banner}export const persistedOperations = {\n${workerEntries}\n} as const\n`,
  ),
  writeFile(
    webOutput,
    `${banner}export const persistedOperationIds = {\n${webEntries}\n} as const\n`,
  ),
])
